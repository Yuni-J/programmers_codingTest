/* 멸종위기의 대장균 찾기 */

WITH RECURSIVE GEN AS (
    SELECT ID, 1 AS GENERATION
    FROM ECOLI_DATA 
    WHERE PARENT_ID IS NULL
    
    UNION ALL
    
    SELECT E.ID, G.GENERATION + 1
    FROM ECOLI_DATA AS E
    JOIN GEN AS G 
        ON E.PARENT_ID = G.ID
)

SELECT 
    COUNT(*) AS COUNT
    , GENERATION
FROM GEN AS G
LEFT JOIN ECOLI_DATA AS E
    ON G.ID = E.PARENT_ID
WHERE E.ID IS NULL
GROUP BY GENERATION
ORDER BY GENERATION;
